// A game's sound pack (Decision 33): one spec → every file rendered or fetched, each with its licence
// sidecar, plus sound.json (what the runtimes read: looping layers that follow game values, events,
// seeded music stems with an intensity ladder, stings) and CREDITS.md. Godot (studio/sound.gd) and the
// web (studio/sound.ts) read the same sound.json, so a pack sounds the same in both engines.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { writeWav, toMono, seamJump, scale, type Channels } from './dsp.ts';
import { sfx, SFX_KINDS } from './sfx.ts';
import { bed, loopFromRecording, BED_KINDS } from './ambience.ts';
import { plan, renderStems, sting, lufs, LEVELS, STEMS, FADER, type Stem, type Plan } from './music.ts';
import { fetchEntry, licenceOf } from './library.ts';
import { writeSidecar, creditsMarkdown, type Licence } from './ledger.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const Follow = z.object({ value: z.string(), gain: z.tuple([z.number(), z.number()]).optional(), lowpass: z.tuple([z.number(), z.number()]).optional(), rate: z.tuple([z.number(), z.number()]).optional() });
export const PackSpecZ = z.object({
  title: z.string(),
  owner: z.string().describe('who the generated sounds belong to (SPDX-FileCopyrightText)'),
  licence: z.string().default('CC0-1.0').describe('licence for the sounds the studio generates'),
  values: z.record(z.string(), z.number()).default({}),
  layers: z.array(z.object({
    id: z.string().regex(/^[a-z0-9-]+$/), gain: z.number().default(1), follow: Follow.optional(), seconds: z.number().default(8),
    bed: z.enum(BED_KINDS).optional(), library: z.string().optional(), start: z.number().optional(), seed: z.union([z.string(), z.number()]).optional(),
  })).default([]),
  events: z.record(z.string(), z.object({
    sounds: z.array(z.object({ kind: z.string(), seed: z.union([z.string(), z.number()]), opts: z.record(z.string(), z.any()).optional() })).optional(),
    library: z.string().optional(), gain: z.number().default(1), pitch: z.tuple([z.number(), z.number()]).optional(),
  })).default({}),
  music: z.object({
    seed: z.union([z.string(), z.number()]), mood: z.enum(['warm', 'night', 'forge', 'bright']).optional(), bpm: z.number().optional(), bars: z.number().default(8),
    value: z.string().default('intensity').describe('the game value (0..1) that walks the intensity ladder'), gain: z.number().default(0.7),
    levels: z.array(z.record(z.string(), z.number())).optional(), stings: z.array(z.enum(['won', 'lost', 'hit'])).default([]),
  }).optional(),
});
export type PackSpec = z.input<typeof PackSpecZ>;

export interface PackManifest {
  version: 1; title: string; values: Record<string, number>;
  layers: Array<{ id: string; file: string; gain: number; follow?: z.infer<typeof Follow> }>;
  events: Record<string, { files: string[]; gain: number; pitch?: [number, number] }>;
  music?: { file: string; bpm: number; bars: number; beatsPerBar: 4; barSeconds: number; loopSeconds: number; key: string; progression: string[]; value: string; gain: number; levels: Array<Record<string, number>>; stems: Record<string, string>; stings: Record<string, string> };
  files: Record<string, Licence>;
}

/** Render or fetch everything a spec asks for into `out` (assets/studio/sound/). */
export async function buildPack(specIn: PackSpec, out: string, log: (s: string) => void = () => {}): Promise<{ manifest: PackManifest; report: any }> {
  const spec = PackSpecZ.parse(specIn);
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(path.join(out, 'music'), { recursive: true });
  const year = new Date().getFullYear();
  const own = (source: Licence['source'], how: string): Licence => ({ spdx: spec.licence, copyright: `${year} ${spec.owner} (generated by the studio)`, source, how });
  const m: PackManifest = { version: 1, title: spec.title, values: spec.values, layers: [], events: {}, files: {} };
  const report: any = { layers: {}, events: {}, music: null };
  const put = (rel: string, audio: Channels, l: Licence) => { const f = path.join(out, rel); writeWav(f, audio); writeSidecar(f, l); m.files[rel] = l; return rel; };

  for (const L of spec.layers) {
    let audio: Channels, lic: Licence;
    if (L.library) { const { wav, entry } = await fetchEntry(L.library); audio = loopFromRecording(wav, L.seconds, L.start); lic = { ...licenceOf(entry), how: `${licenceOf(entry).how} (a ${L.seconds}s loop cut and crossfaded)` }; }
    else if (L.bed) { audio = bed(L.bed, L.seed ?? L.id, L.seconds); lic = own('ambience', `bed ${L.bed} seed ${L.seed ?? L.id}`); }
    else throw new Error(`layer ${L.id}: give it a bed (${BED_KINDS.join(', ')}) or a library sound`);
    m.layers.push({ id: L.id, file: put(`${L.id}.wav`, audio, lic), gain: L.gain, ...(L.follow ? { follow: L.follow } : {}) });
    report.layers[L.id] = { seconds: +(audio[0].length / 44100).toFixed(2), seamJump: +seamJump(audio).toFixed(2), lufs: lufs(audio), source: lic.source };
    log(`layer ${L.id}`);
  }
  for (const [name, E] of Object.entries(spec.events)) {
    const files: string[] = [];
    if (E.library) { const { wav, entry } = await fetchEntry(E.library); const rel = `${name}-lib.wav`; fs.copyFileSync(wav, path.join(out, rel)); writeSidecar(path.join(out, rel), licenceOf(entry)); m.files[rel] = licenceOf(entry); files.push(rel); }
    for (const [i, s] of (E.sounds ?? []).entries()) {
      if (!SFX_KINDS.includes(s.kind) && s.kind !== 'sfxr') throw new Error(`event ${name}: unknown kind ${s.kind}`);
      const a = sfx(s.kind, s.seed, s.opts ?? {});
      files.push(put(`${name}-${i + 1}.wav`, a.length === 2 && s.kind !== 'clink' && s.kind !== 'chime' && s.kind !== 'impact' && s.kind !== 'riser' ? toMono(a) : a, own('synth', `sfx ${s.kind} seed ${s.seed}`)));
    }
    if (!files.length) throw new Error(`event ${name}: no sounds`);
    m.events[name] = { files, gain: E.gain, ...(E.pitch ? { pitch: E.pitch } : {}) };
    report.events[name] = files.length;
  }
  if (spec.music) {
    const M = spec.music;
    const p: Plan = plan({ seed: M.seed, mood: M.mood, bpm: M.bpm, bars: M.bars });
    const stems = renderStems(p);
    const rel: Record<string, string> = {};
    for (const s of STEMS) {
      // stems are stored pre-balanced (the house faders baked in), mono where width adds little
      const a = scale(s === 'pad' || s === 'lead' || s === 'arp' ? stems[s] : toMono(stems[s]), FADER[s] * 0.5);
      rel[s] = put(`music/${s}.wav`, a, own('stems', `stem ${s} of seed ${M.seed} (${p.keyName}, ${p.bpm} bpm, ${p.progression.join('–')})`));
    }
    const stings: Record<string, string> = {};
    for (const k of M.stings) stings[k] = put(`music/sting-${k}.wav`, sting(p, k), own('stems', `sting ${k} of seed ${M.seed}`));
    m.music = { file: 'music', bpm: p.bpm, bars: p.bars, beatsPerBar: 4, barSeconds: p.barSeconds, loopSeconds: p.loopSeconds, key: p.keyName, progression: p.progression, value: M.value, gain: M.gain, levels: M.levels ?? LEVELS as any, stems: rel, stings };
    report.music = { key: p.keyName, bpm: p.bpm, progression: p.progression, loopSeconds: p.loopSeconds, seams: Object.fromEntries(STEMS.map((s) => [s, +seamJump(stems[s]).toFixed(2)])) };
    log('music');
  }
  fs.writeFileSync(path.join(out, 'sound.json'), JSON.stringify(m, null, 2) + '\n');
  fs.writeFileSync(path.join(out, 'CREDITS.md'), creditsMarkdown(spec.title, Object.entries(m.files).map(([file, licence]) => ({ file, licence }))));
  return { manifest: m, report };
}

/** Copy the runtimes into a game (managed files: overwritten on every pack build). */
export function writeRuntimes(gameDir: string, engine: 'godot' | 'web'): string[] {
  const studio = path.join(gameDir, 'studio');
  fs.mkdirSync(studio, { recursive: true });
  const src = engine === 'godot' ? 'sound.gd' : 'sound-web.ts', dst = path.join(studio, engine === 'godot' ? 'sound.gd' : 'sound.ts');
  fs.copyFileSync(path.join(HERE, '..', 'runtime', src), dst);
  return [dst];
}

/** Read a game's pack spec (sound/sound-spec.json), build into assets/studio/sound/, add the runtime. */
export async function buildGamePack(gameDir: string, engine: 'godot' | 'web', spec?: PackSpec, log?: (s: string) => void) {
  const specFile = path.join(gameDir, 'sound', 'sound-spec.json');
  const s = spec ?? (fs.existsSync(specFile) ? JSON.parse(fs.readFileSync(specFile, 'utf8')) : null);
  if (!s) throw Object.assign(new Error(`no sound spec: ${path.relative(process.cwd(), specFile)}`), { hint: 'write sound/sound-spec.json (see studio sound help) or pass --spec' });
  if (spec) { fs.mkdirSync(path.dirname(specFile), { recursive: true }); fs.writeFileSync(specFile, JSON.stringify(spec, null, 2) + '\n'); }
  const r = await buildPack(s, path.join(gameDir, 'assets', 'studio', 'sound'), log);
  return { ...r, runtimes: writeRuntimes(gameDir, engine) };
}
