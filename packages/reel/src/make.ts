// The reel pipeline: music (generated seeded track, or a file) → beats (librosa) → capture (Godot movie
// mode / web fixed step) → cut (beats, cards, one ffmpeg recipe per shape) → review stills and sheet.
// Every step reads the reel file, so re-running `studio reel cut` after an edit re-cuts in seconds.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { parseReel, cutToBeats, cutErrors, ASPECTS, type Reel, type Aspect, type Cut } from './reel.ts';
import { captureGodot, captureWeb } from './capture.ts';
import { renderCards, type Card } from './titles.ts';
import { runRecipe } from './recipe.ts';
import { plan, renderStems, arrange, toLoudness, type Section } from '../../sound/src/music.ts';
import { sfx } from '../../sound/src/sfx.ts';
import { writeWav, softClip } from '../../sound/src/dsp.ts';
import { writeSidecar } from '../../sound/src/ledger.ts';
import { detectBeats, gridError, type BeatGrid } from '../../sound/src/beats.ts';
import { listen } from '../../sound/src/listen.ts';

export const readReel = (file: string): Reel => parseReel(JSON.parse(fs.readFileSync(file, 'utf8')));
export const workDirFor = (gameDir: string, reel: Reel) => path.join(gameDir, '.studio', 'reel', reel.id);

/** The beats the edit needs, as whole bars (4/4). */
export function editBeats(reel: Reel) { return reel.edit.reduce((s, e) => s + e.beats, 0) + (reel.endCard?.beats ?? 0); }

/** The generated track: the reel's sections (or intro/build/drop/end over the edit's length), a riser
 *  into the drop and hits on its first bar and the end card; then librosa finds the beats we cut on. */
export function reelMusic(reel: Reel, work: string, owner = 'the game\'s authors') {
  fs.mkdirSync(work, { recursive: true });
  const wav = path.join(work, 'music.wav');
  let known: { bpm: number; bars: Array<{ bar: number; t: number; label?: string }> } | null = null;
  if (reel.music.file) fs.copyFileSync(reel.music.file, wav);
  else {
    const M = reel.music, bars = Math.ceil(editBeats(reel) / 4);
    const sections: Section[] = (M.sections as Section[] | undefined) ?? [
      { bars: Math.max(1, Math.round(bars * 0.25)), label: 'intro', mix: { pad: 0.9, arp: 0.55 } },
      { bars: Math.max(1, Math.round(bars * 0.25)), label: 'build', mix: { pad: 0.85, arp: 0.75, bass: 0.9, hats: 0.7 } },
      { bars: Math.max(1, bars - 2 * Math.round(bars * 0.25) - 2), label: 'drop', riser: true, hit: true, mix: { pad: 0.75, arp: 0.7, bass: 1, hats: 0.85, beat: 1, lead: 0.85 } },
      { bars: 2, label: 'end', hit: true, mix: { pad: 0.85, arp: 0.35, bass: 0.6 } },
    ];
    const p = plan({ seed: M.seed, mood: M.mood, bpm: M.bpm, bars: 8 });
    const song = arrange(p, renderStems(p), sections, { riser: sfx('riser', `${M.seed}-riser`, { seconds: p.barSeconds * 2 }), impact: sfx('impact', `${M.seed}-hit`) });
    writeWav(wav, softClip(toLoudness(song.audio, -15), 0.94));
    writeSidecar(wav, { spdx: 'CC0-1.0', copyright: `${new Date().getFullYear()} ${owner} (generated by the studio)`, source: 'stems', how: `trailer track: seed ${M.seed}, ${p.keyName}, ${p.bpm} bpm, ${p.progression.join('–')}; sections ${sections.map((s) => `${s.label ?? ''}×${s.bars}`).join(', ')}` });
    known = { bpm: p.bpm, bars: song.bars };
    fs.writeFileSync(path.join(work, 'music-plan.json'), JSON.stringify({ key: p.keyName, bpm: p.bpm, progression: p.progression, sections, bars: song.bars, seconds: song.seconds }, null, 2));
  }
  const grid: BeatGrid = detectBeats(wav, reel.music.bpm);
  fs.writeFileSync(path.join(work, 'beats.json'), JSON.stringify(grid, null, 2));
  const report = listen(wav, { picture: path.join(work, 'music.png') });
  return { wav, grid: { bpm: grid.bpm, beats: grid.beats.length, tool: grid.tool }, ...(known ? { againstKnownGrid: gridError(grid, known.bpm, 0) } : {}), listen: report };
}

/** The edit's cards (titles, captions, end card). */
export function reelCards(cut: Cut): Card[] {
  const cards: Card[] = [];
  for (const s of cut.shots) {
    if (s.title) cards.push({ id: `title-${s.index}`, kind: 'title', text: s.title.text, sub: s.title.sub });
    if (s.caption) cards.push({ id: `caption-${s.index}`, kind: 'caption', text: s.caption });
  }
  if (cut.endCard) cards.push({ id: 'end', kind: 'end', text: cut.endCard.title, sub: cut.endCard.sub, credit: cut.endCard.credit });
  return cards;
}

/** Use the detected beats, but snap them onto the steady grid they imply (librosa jitters by a frame or
 *  two; a generated track is perfectly steady), keeping the phase librosa found. */
export function steadyBeats(grid: BeatGrid, duration: number): number[] {
  const b = grid.beats, n = b.length;
  if (n < 8) return b;
  // the period: median gap between neighbouring detections (quiet passages drop beats, so ignore gaps
  // that span several); the phase: circular mean of every beat's position within that period
  const gaps = b.slice(1).map((t, i) => t - b[i]).sort((x, y) => x - y), med = gaps[Math.floor(gaps.length / 2)];
  const good = b.slice(1).map((t, i) => [t - b[i], i] as const).filter(([g]) => Math.abs(g - med) < med * 0.15);
  let period = good.reduce((s, [g]) => s + g, 0) / good.length;
  // refine the period over the whole span: count the beats between first and last detection
  const span = b[n - 1] - b[0], k = Math.round(span / period); if (k > 0) period = span / k;
  let sx = 0, sy = 0;
  for (const t of b) { const a = (2 * Math.PI * t) / period; sx += Math.cos(a); sy += Math.sin(a); }
  const ph = ((Math.atan2(sy, sx) / (2 * Math.PI)) * period + period) % period;
  const first = ph > period * 0.9 ? ph - period : ph;
  const out: number[] = [];
  for (let t = first; t <= duration + 1e-6; t += period) out.push(+t.toFixed(4));
  return out;
}

export async function reelCut(reel: Reel, work: string, out: string, aspects: readonly Aspect[] = ASPECTS, engine: 'godot' | 'web' = 'godot') {
  const gridFile = path.join(work, 'beats.json');
  if (!fs.existsSync(gridFile)) throw Object.assign(new Error('no beats yet'), { hint: 'studio reel music first' });
  const grid: BeatGrid = JSON.parse(fs.readFileSync(gridFile, 'utf8'));
  const beats = steadyBeats(grid, grid.duration);
  // the first cut lands on beat 0 of the steady grid (bar 1 of the music)
  const cut = cutToBeats(reel, beats);
  const takesDir = path.join(work, engine === 'godot' ? 'takes' : 'takes-web');
  const takes: Record<string, string> = {};
  for (const s of cut.shots) { const f = path.join(takesDir, `${s.take}.mp4`); if (!fs.existsSync(f)) throw Object.assign(new Error(`take ${s.take} isn't captured`), { hint: `studio reel capture --takes ${s.take}` }); takes[s.take] = f; }
  fs.mkdirSync(out, { recursive: true });
  const cardFiles = await renderCards(reelCards(cut), path.join(work, 'cards'), aspects);
  const videos = [];
  for (const a of aspects) {
    const v = path.join(out, `${reel.id}-${a.replace(':', 'x')}.mp4`);
    videos.push(runRecipe(reel, cut, a, { takes, music: path.join(work, 'music.wav'), cards: cardFiles[a] }, out, v));
  }
  // review: one still per shot (its middle) per shape, and a sheet per shape
  const stills: Record<string, string[]> = {};
  for (const v of videos) {
    const tag = v.aspect.replace(':', 'x'), dir = path.join(out, 'stills', tag);
    fs.mkdirSync(dir, { recursive: true });
    const times = [...cut.shots.map((s) => (s.start + s.end) / 2), ...(cut.endCard ? [(cut.endCard.start + cut.endCard.end) / 2] : [])];
    stills[tag] = times.map((t, i) => { const f = path.join(dir, `${String(i + 1).padStart(2, '0')}.jpg`); spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-ss', t.toFixed(3), '-i', v.video, '-frames:v', '1', '-q:v', '3', f]); return f; });
    const cols = tag === '9x16' ? 6 : 4, w = tag === '9x16' ? 270 : tag === '1x1' ? 360 : 480;
    const sheet = path.join(out, `sheet-${tag}.jpg`);
    const inputs = stills[tag].flatMap((f) => ['-i', f]);
    const n = stills[tag].length, rows = Math.ceil(n / cols);
    const layout = stills[tag].map((_, i) => `${(i % cols) === 0 ? '0' : Array.from({ length: i % cols }, () => 'w0').join('+')}_${Math.floor(i / cols) === 0 ? '0' : Array.from({ length: Math.floor(i / cols) }, () => 'h0').join('+')}`).join('|');
    spawnSync('ffmpeg', ['-y', '-loglevel', 'error', ...inputs, '-filter_complex', `${stills[tag].map((_, i) => `[${i}:v]scale=${w}:-2[s${i}]`).join(';')};${stills[tag].map((_, i) => `[s${i}]`).join('')}xstack=inputs=${n}:layout=${layout}:fill=black`, '-q:v', '3', sheet]);
    void rows;
  }
  const errs = cutErrors(cut, grid.beats);
  const report = { reel: reel.id, engine, duration: cut.duration, bpm: cut.bpm, shots: cut.shots.map((s) => ({ n: s.index, take: s.take, start: s.start, end: s.end, in: s.in, out: s.out, beats: s.beats, caption: s.caption ?? s.title?.text })), endCard: cut.endCard, cutsVsDetectedBeatsMs: { max: Math.max(...errs), median: errs.sort((a, b) => a - b)[Math.floor(errs.length / 2)] }, warnings: cut.warnings, videos, stills };
  fs.writeFileSync(path.join(out, `${reel.id}-cut.json`), JSON.stringify(report, null, 2));
  return report;
}

export async function reelCapture(reel: Reel, gameDir: string, work: string, opts: { engine?: 'godot' | 'web'; takes?: string[]; size?: number } = {}, log?: (s: string) => void) {
  return (opts.engine ?? 'godot') === 'godot' ? captureGodot(opts.size ? { ...reel, size: opts.size } : reel, gameDir, work, opts.takes, log) : captureWeb(reel, gameDir, work, opts.takes, log, opts.size);
}

/** A storyboard of the captured takes: first, middle and last frame of each, one row per take. */
export function storyboard(reel: Reel, work: string, out: string, engine: 'godot' | 'web' = 'godot') {
  const dir = path.join(work, engine === 'godot' ? 'takes' : 'takes-web'), tmp = path.join(work, 'board');
  fs.mkdirSync(tmp, { recursive: true });
  const files: string[] = [];
  for (const t of reel.takes) {
    const f = path.join(dir, `${t.id}.mp4`); if (!fs.existsSync(f)) continue;
    for (const [k, u] of [0.05, 0.5, 0.95].entries()) { const o = path.join(tmp, `${t.id}-${k}.jpg`); spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-ss', (u * t.seconds).toFixed(2), '-i', f, '-frames:v', '1', '-vf', 'scale=360:360', '-q:v', '4', o]); files.push(o); }
  }
  if (!files.length) return null;
  const n = files.length, cols = 3;
  const layout = files.map((_, i) => `${(i % cols) === 0 ? '0' : Array.from({ length: i % cols }, () => 'w0').join('+')}_${Math.floor(i / cols) === 0 ? '0' : Array.from({ length: Math.floor(i / cols) }, () => 'h0').join('+')}`).join('|');
  spawnSync('ffmpeg', ['-y', '-loglevel', 'error', ...files.flatMap((f) => ['-i', f]), '-filter_complex', `${files.map((_, i) => `[${i}:v]`).join('')}xstack=inputs=${n}:layout=${layout}`, '-q:v', '3', out]);
  return out;
}
